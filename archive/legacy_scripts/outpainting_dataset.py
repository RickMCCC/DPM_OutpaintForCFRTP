"""
PyTorch Dataset for outpainting triplets generated by prepare_outpainting_data.py

Expected directory structure under `root_dir`:
  root_dir/
    init/
    full_mask/
    target/

Each file shares the same basename across the three subfolders, e.g.:
  init/foo_corner0_sub1_c300_s100.png
  full_mask/foo_corner0_sub1_c300_s100.png
  target/foo_corner0_sub1_c300_s100.png

Returns grayscale tensors:
  init:   float32 in [-1, 1], shape (1, H, W)
  mask:   float32 in {0, 1}, shape (1, H, W)  (1 means unknown region to be generated)
  target: float32 in [-1, 1], shape (1, H, W)
"""

from pathlib import Path
from typing import Optional, Callable, List, Dict

import numpy as np
import torch
from torch.utils.data import Dataset
from PIL import Image


def _load_gray_to_minus1_1(path: Path) -> torch.Tensor:
    img = Image.open(path).convert("L")
    arr = np.asarray(img, dtype=np.float32) / 255.0
    arr = arr * 2.0 - 1.0
    t = torch.from_numpy(arr)[None, ...]  # (1,H,W)
    return t


def _load_mask_to_01(path: Path) -> torch.Tensor:
    img = Image.open(path).convert("L")
    arr = np.asarray(img, dtype=np.float32) / 255.0
    arr = np.clip(arr, 0.0, 1.0)
    t = torch.from_numpy(arr)[None, ...]  # (1,H,W)
    return t


class OutpaintingTripletDataset(Dataset):
    def __init__(
        self,
        root_dir: str,
        names: Optional[List[str]] = None,
        transform_init: Optional[Callable[[torch.Tensor], torch.Tensor]] = None,
        transform_target: Optional[Callable[[torch.Tensor], torch.Tensor]] = None,
        transform_mask: Optional[Callable[[torch.Tensor], torch.Tensor]] = None,
    ) -> None:
        super().__init__()
        self.root = Path(root_dir)
        self.init_dir = self.root / "init"
        self.mask_dir = self.root / "full_mask"
        self.target_dir = self.root / "target"

        assert self.init_dir.is_dir(), f"missing {self.init_dir}"
        assert self.mask_dir.is_dir(), f"missing {self.mask_dir}"
        assert self.target_dir.is_dir(), f"missing {self.target_dir}"

        if names is None:
            # infer names by intersection of basenames across three folders
            inits = {p.name for p in self.init_dir.glob("*.png")}
            masks = {p.name for p in self.mask_dir.glob("*.png")}
            targets = {p.name for p in self.target_dir.glob("*.png")}
            common = sorted(list(inits & masks & targets))
            self.names = common
        else:
            self.names = names

        self.transform_init = transform_init
        self.transform_target = transform_target
        self.transform_mask = transform_mask

    def __len__(self) -> int:
        return len(self.names)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        name = self.names[idx]
        init_path = self.init_dir / name
        mask_path = self.mask_dir / name
        target_path = self.target_dir / name

        init = _load_gray_to_minus1_1(init_path)
        mask = _load_mask_to_01(mask_path)
        target = _load_gray_to_minus1_1(target_path)

        if self.transform_init is not None:
            init = self.transform_init(init)
        if self.transform_mask is not None:
            mask = self.transform_mask(mask)
        if self.transform_target is not None:
            target = self.transform_target(target)

        return {"name": name, "init": init, "mask": mask, "target": target}


