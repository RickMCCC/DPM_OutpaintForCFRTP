"""
PyTorch Dataset for 3D outpainting triplets generated by prepare_outpainting_3d_data.py

Expected directory structure under `root_dir`:
  root_dir/
    init/
    full_mask/
    target/

Each triplet consists of multiple Z-slice PNG files with naming pattern:
  init/z0000_y0000_x0000_c128_s32_z000.png
  init/z0000_y0000_x0000_c128_s32_z001.png
  ...
  init/z0000_y0000_x0000_c128_s32_z127.png

Returns 3D grayscale tensors:
  init:   float32 in [-1, 1], shape (1, D, H, W)  where D is depth (Z slices)
  mask:   float32 in [0, 1], shape (1, D, H, W)   (1 means unknown region to be generated)
  target: float32 in [-1, 1], shape (1, D, H, W)
"""

from pathlib import Path
from typing import Optional, Callable, List, Dict

import numpy as np
import torch
from torch.utils.data import Dataset
from PIL import Image


def sanitize_triplet(
    init: torch.Tensor,
    mask: torch.Tensor,
    target: torch.Tensor,
) -> Dict[str, torch.Tensor]:
    """Enforce the numeric contract shared by PNG and cached datasets."""
    init = init.to(dtype=torch.float32)
    target = target.to(dtype=torch.float32)
    mask = (mask.to(dtype=torch.float32) >= 0.5).to(dtype=torch.float32)

    if not torch.isfinite(init).all() or not torch.isfinite(target).all():
        raise ValueError("init and target must contain only finite values")
    if init.min() < -1.0001 or init.max() > 1.0001:
        raise ValueError("init must be normalized to [-1, 1]")
    if target.min() < -1.0001 or target.max() > 1.0001:
        raise ValueError("target must be normalized to [-1, 1]")

    # Unknown voxels are neutral in normalized space. This avoids encoding an
    # out-of-distribution volume whose 87.5% unknown area is saturated at -1.
    init = init * (1.0 - mask)
    return {"init": init, "mask": mask, "target": target}


def _load_gray_to_minus1_1(path: Path) -> torch.Tensor:
    """Load a single 2D slice and convert to [-1, 1] range"""
    img = Image.open(path).convert("L")
    arr = np.asarray(img, dtype=np.float32) / 255.0
    arr = arr * 2.0 - 1.0
    t = torch.from_numpy(arr)  # (H, W)
    return t


def _load_mask_to_01(path: Path) -> torch.Tensor:
    """Load a single 2D mask slice and convert to [0, 1] range"""
    img = Image.open(path).convert("L")
    arr = np.asarray(img, dtype=np.float32) / 255.0
    arr = np.clip(arr, 0.0, 1.0)
    t = torch.from_numpy(arr)  # (H, W)
    return t


def _load_volume_slices(base_name: str, base_dir: Path, load_fn) -> torch.Tensor:
    """
    Load all Z slices for a given base name and stack them into a 3D volume.
    
    Args:
        base_name: Base name without _z{idx}.png suffix (e.g., "z0000_y0000_x0000_c128_s32")
        base_dir: Directory containing the slice files
        load_fn: Function to load a single slice (returns (H, W) tensor)
    
    Returns:
        Tensor of shape (D, H, W) where D is the number of slices
    """
    # Find all slices for this base name
    pattern = f"{base_name}_z*.png"
    slice_files = sorted(base_dir.glob(pattern))
    
    if not slice_files:
        raise FileNotFoundError(f"No slices found for {base_name} in {base_dir}")
    
    # Load all slices
    slices = []
    for slice_file in slice_files:
        slice_tensor = load_fn(slice_file)
        slices.append(slice_tensor)
    
    # Stack slices along depth dimension: (D, H, W)
    volume = torch.stack(slices, dim=0)
    return volume


class Outpainting3DTripletDataset(Dataset):
    def __init__(
        self,
        root_dir: str,
        names: Optional[List[str]] = None,
        transform_init: Optional[Callable[[torch.Tensor], torch.Tensor]] = None,
        transform_target: Optional[Callable[[torch.Tensor], torch.Tensor]] = None,
        transform_mask: Optional[Callable[[torch.Tensor], torch.Tensor]] = None,
    ) -> None:
        super().__init__()
        self.root = Path(root_dir)
        self.init_dir = self.root / "init"
        self.mask_dir = self.root / "full_mask"
        self.target_dir = self.root / "target"

        assert self.init_dir.is_dir(), f"missing {self.init_dir}"
        assert self.mask_dir.is_dir(), f"missing {self.mask_dir}"
        assert self.target_dir.is_dir(), f"missing {self.target_dir}"

        if names is None:
            # Find all base names by extracting unique prefixes from slice files
            # Pattern: {base_name}_z{idx}.png
            init_files = list(self.init_dir.glob("*_z*.png"))
            base_names = set()
            for f in init_files:
                # Extract base name: remove _z{idx}.png suffix
                name = f.stem  # e.g., "z0000_y0000_x0000_c128_s32_z000"
                base_name = "_".join(name.split("_")[:-1])  # Remove last _z{idx} part
                base_names.add(base_name)
            
            # Verify that all three directories have slices for these base names
            valid_base_names = []
            for base_name in sorted(base_names):
                # Check if all three directories have slices for this base name
                init_slices = list(self.init_dir.glob(f"{base_name}_z*.png"))
                mask_slices = list(self.mask_dir.glob(f"{base_name}_z*.png"))
                target_slices = list(self.target_dir.glob(f"{base_name}_z*.png"))
                
                if init_slices and mask_slices and target_slices:
                    # Verify slice counts match
                    if len(init_slices) == len(mask_slices) == len(target_slices):
                        valid_base_names.append(base_name)
            
            self.names = valid_base_names
        else:
            self.names = names

        self.transform_init = transform_init
        self.transform_target = transform_target
        self.transform_mask = transform_mask

    def __len__(self) -> int:
        return len(self.names)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        base_name = self.names[idx]
        
        # Load 3D volumes: (D, H, W)
        init = _load_volume_slices(base_name, self.init_dir, _load_gray_to_minus1_1)
        mask = _load_volume_slices(base_name, self.mask_dir, _load_mask_to_01)
        target = _load_volume_slices(base_name, self.target_dir, _load_gray_to_minus1_1)
        
        # Add channel dimension: (1, D, H, W)
        init = init[None, ...]
        mask = mask[None, ...]
        target = target[None, ...]

        if self.transform_init is not None:
            init = self.transform_init(init)
        if self.transform_mask is not None:
            mask = self.transform_mask(mask)
        if self.transform_target is not None:
            target = self.transform_target(target)

        return {"name": base_name, **sanitize_triplet(init, mask, target)}


class CachedOutpainting3DDataset(Dataset):
    """从预缓存的 .pt 文件加载三元组，消除 PNG I/O 瓶颈。

    每个 .pt 文件包含: {"init": (1,D,H,W), "mask": (1,D,H,W), "target": (1,D,H,W)}
    """

    def __init__(self, cache_dir: str) -> None:
        super().__init__()
        self.cache_dir = Path(cache_dir)
        manifest_file = self.cache_dir / "manifest.json"
        if manifest_file.is_file():
            import json
            with open(manifest_file) as f:
                manifest = json.load(f)
            self.names = manifest["names"]
        else:
            self.names = sorted(
                f.stem for f in self.cache_dir.glob("*.pt")
            )

    def __len__(self) -> int:
        return len(self.names)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        data = torch.load(self.cache_dir / f"{self.names[idx]}.pt")
        init = data["init"]
        mask = data["mask"]
        target = data["target"]
        if init.dtype == torch.uint8:
            init = init.to(dtype=torch.float32) / 127.5 - 1.0
        if target.dtype == torch.uint8:
            target = target.to(dtype=torch.float32) / 127.5 - 1.0
        if mask.dtype == torch.uint8:
            mask = mask.to(dtype=torch.float32)
        triplet = sanitize_triplet(init, mask, target)
        return {"name": self.names[idx], **triplet}
